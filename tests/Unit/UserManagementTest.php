<?php

declare(strict_types=1);

namespace Tests\Unit;

use App\Http\Controllers\AdminController;
use App\Support\Database;
use App\Support\Session;
use PDO;
use PHPUnit\Framework\TestCase;

class TestableAdminController extends AdminController
{
    public ?string $lastRedirect = null;

    protected function redirect(string $path, int $status = 302): never
    {
        $this->lastRedirect = $path;
        throw new \RuntimeException("REDIRECT: {$path}");
    }
}

class UserManagementTest extends TestCase
{
    private PDO $pdo;
    private TestableAdminController $controller;

    protected function setUp(): void
    {
        require_once dirname(__DIR__, 2) . '/src/bootstrap.php';

        $this->pdo = new PDO('sqlite::memory:');
        $this->pdo->setAttribute(PDO::ATTR_ERRMODE, PDO::ERRMODE_EXCEPTION);

        $this->pdo->exec("
            CREATE TABLE admin (
                id_admin INTEGER PRIMARY KEY AUTOINCREMENT,
                first_name TEXT,
                last_name TEXT,
                username TEXT NOT NULL,
                email TEXT NOT NULL,
                password TEXT NULL,
                status TEXT NOT NULL DEFAULT 'approved',
                role TEXT NOT NULL DEFAULT 'ADMIN DASHBOARD',
                unit_id INTEGER NULL,
                is_active INTEGER NOT NULL DEFAULT 1,
                must_change_password INTEGER NOT NULL DEFAULT 0,
                failed_attempts INTEGER NOT NULL DEFAULT 0,
                locked_until DATETIME NULL,
                last_login_at DATETIME NULL,
                created_at DATETIME DEFAULT CURRENT_TIMESTAMP,
                email_verified INTEGER DEFAULT 1,
                verification_token TEXT NULL,
                verification_expires DATETIME NULL
            )
        ");

        $this->pdo->exec("
            CREATE TABLE units (
                id INTEGER PRIMARY KEY AUTOINCREMENT,
                nama TEXT NOT NULL
            )
        ");

        $this->pdo->exec("
            CREATE TABLE sessions (
                token TEXT PRIMARY KEY,
                user_id INTEGER NOT NULL,
                expires_at DATETIME NOT NULL,
                created_at DATETIME DEFAULT CURRENT_TIMESTAMP,
                ip TEXT NULL,
                user_agent TEXT NULL
            )
        ");

        $this->pdo->exec("
            CREATE TABLE audit_log (
                id INTEGER PRIMARY KEY AUTOINCREMENT,
                user_id INTEGER NULL,
                action TEXT NOT NULL,
                entity TEXT NOT NULL,
                entity_id INTEGER NULL,
                meta TEXT NULL,
                created_at DATETIME DEFAULT CURRENT_TIMESTAMP
            )
        ");

        // Seed units
        $this->pdo->exec("INSERT INTO units (id, nama) VALUES (1, 'Fungsi Distribusi'), (2, 'Fungsi Sosial')");

        // Seed 1 active ADMIN IT (ID 1)
        $this->pdo->exec("
            INSERT INTO admin (id_admin, username, email, role, status, is_active)
            VALUES (1, 'superadmin', 'admin@bps.go.id', 'ADMIN IT', 'approved', 1)
        ");

        // Seed 1 regular user (ID 2)
        $this->pdo->exec("
            INSERT INTO admin (id_admin, username, email, role, status, is_active, unit_id)
            VALUES (2, 'operator1', 'operator@bps.go.id', 'ADMIN DASHBOARD', 'approved', 1, 1)
        ");

        Database::setPdo($this->pdo);

        Session::destroy();
        $_SESSION = [];
        Session::start();
        Session::set('admin_id', 1);
        Session::set('admin_username', 'superadmin');
        Session::set('admin_role', 'ADMIN IT');
        Session::set('csrf_token', 'test_csrf_token');

        $this->controller = new TestableAdminController();
    }

    protected function tearDown(): void
    {
        Session::destroy();
        $_SESSION = [];
        $_POST = [];
        Database::setPdo(null);
    }

    public function testManageAdminLoadsAdminsAndUnits(): void
    {
        $output = $this->controller->manageAdmin();
        $this->assertStringContainsString('superadmin', $output);
        $this->assertStringContainsString('operator1', $output);
        $this->assertStringContainsString('Fungsi Distribusi', $output);
    }

    public function testStoreUserWithAutoGeneratedTempPassword(): void
    {
        $_POST = [
            'csrf_token' => 'test_csrf_token',
            'username'   => 'user_baru',
            'email'      => 'baru@bps.go.id',
            'first_name' => 'Budi',
            'last_name'  => 'Baru',
            'role'       => 'ADMIN DASHBOARD',
            'unit_id'    => '2',
            'password'   => '', // should generate temp password
        ];

        try {
            $this->controller->storeUser();
        } catch (\RuntimeException $e) {
            $this->assertStringContainsString('REDIRECT', $e->getMessage());
        }

        $stmt = $this->pdo->prepare("SELECT * FROM admin WHERE username = ?");
        $stmt->execute(['user_baru']);
        $user = $stmt->fetch(PDO::FETCH_ASSOC);

        $this->assertNotEmpty($user);
        $this->assertSame('baru@bps.go.id', $user['email']);
        $this->assertSame('ADMIN DASHBOARD', $user['role']);
        $this->assertSame(2, (int)$user['unit_id']);
        $this->assertSame(1, (int)$user['must_change_password']);
        $this->assertSame(1, (int)$user['is_active']);
        $this->assertNotEmpty($user['password']);

        // Check flash message contains temp password notice
        $flash = flash('success') ?? '';
        $this->assertStringContainsString('Password sementara', $flash);
        $this->assertStringContainsString('Wajib diganti saat login pertama', $flash);
    }

    public function testPreventLastAdminItFromDemotingSelf(): void
    {
        $_POST = [
            'csrf_token'  => 'test_csrf_token',
            'id_admin'    => 1, // superadmin itself (only 1 active ADMIN IT in DB)
            'action'      => 'update_role_unit',
            'new_role'    => 'ADMIN DASHBOARD',
            'new_unit_id' => 1,
        ];

        try {
            $this->controller->actionAdmin();
        } catch (\RuntimeException $e) {
            $this->assertStringContainsString('REDIRECT', $e->getMessage());
        }

        // Role must remain ADMIN IT
        $stmt = $this->pdo->prepare("SELECT role FROM admin WHERE id_admin = 1");
        $stmt->execute();
        $this->assertSame('ADMIN IT', $stmt->fetchColumn());

        $flashError = flash('error') ?? '';
        $this->assertStringContainsString('ADMIN IT terakhir yang aktif', $flashError);
    }

    public function testPreventLastAdminItFromDeactivatingSelf(): void
    {
        $_POST = [
            'csrf_token' => 'test_csrf_token',
            'id_admin'   => 1, // superadmin itself
            'action'     => 'toggle_active',
            'is_active'  => 0,
        ];

        try {
            $this->controller->actionAdmin();
        } catch (\RuntimeException $e) {
            $this->assertStringContainsString('REDIRECT', $e->getMessage());
        }

        // Active must remain 1
        $stmt = $this->pdo->prepare("SELECT is_active FROM admin WHERE id_admin = 1");
        $stmt->execute();
        $this->assertSame(1, (int)$stmt->fetchColumn());

        $flashError = flash('error') ?? '';
        $this->assertStringContainsString('ADMIN IT terakhir yang aktif', $flashError);
    }

    public function testDeactivatingUserTerminatesSessions(): void
    {
        // Insert active session for operator1 (ID 2)
        $token = bin2hex(random_bytes(32));
        $this->pdo->prepare("
            INSERT INTO sessions (token, user_id, expires_at)
            VALUES (?, 2, datetime('now', '+8 hours'))
        ")->execute([$token]);

        $_POST = [
            'csrf_token' => 'test_csrf_token',
            'id_admin'   => 2,
            'action'     => 'toggle_active',
            'is_active'  => 0,
        ];

        try {
            $this->controller->actionAdmin();
        } catch (\RuntimeException $e) {
            $this->assertStringContainsString('REDIRECT', $e->getMessage());
        }

        // Operator1 is now inactive
        $stmt = $this->pdo->prepare("SELECT is_active FROM admin WHERE id_admin = 2");
        $stmt->execute();
        $this->assertSame(0, (int)$stmt->fetchColumn());

        // Session must be purged
        $checkSession = $this->pdo->prepare("SELECT COUNT(*) FROM sessions WHERE token = ?");
        $checkSession->execute([$token]);
        $this->assertSame(0, (int)$checkSession->fetchColumn());
    }

    public function testResetPasswordGeneratesTempPasswordAndPurgesSessions(): void
    {
        // Insert active session for operator1 (ID 2)
        $token = bin2hex(random_bytes(32));
        $this->pdo->prepare("
            INSERT INTO sessions (token, user_id, expires_at)
            VALUES (?, 2, datetime('now', '+8 hours'))
        ")->execute([$token]);

        $_POST = [
            'csrf_token' => 'test_csrf_token',
            'id_admin'   => 2,
            'action'     => 'reset_password',
        ];

        try {
            $this->controller->actionAdmin();
        } catch (\RuntimeException $e) {
            $this->assertStringContainsString('REDIRECT', $e->getMessage());
        }

        $stmt = $this->pdo->prepare("SELECT must_change_password, failed_attempts, locked_until FROM admin WHERE id_admin = 2");
        $stmt->execute();
        $user = $stmt->fetch(PDO::FETCH_ASSOC);

        $this->assertSame(1, (int)$user['must_change_password']);
        $this->assertSame(0, (int)$user['failed_attempts']);
        $this->assertNull($user['locked_until']);

        // Session purged
        $checkSession = $this->pdo->prepare("SELECT COUNT(*) FROM sessions WHERE token = ?");
        $checkSession->execute([$token]);
        $this->assertSame(0, (int)$checkSession->fetchColumn());

        // Flash message contains temp password
        $flash = flash('success') ?? '';
        $this->assertStringContainsString('Password sementara', $flash);
        $this->assertStringContainsString('Pengguna wajib mengganti password saat login', $flash);
    }

    public function testAdminCannotDeleteSelf(): void
    {
        $_POST = [
            'csrf_token' => 'test_csrf_token',
            'id_admin'   => 1, // self
            'action'     => 'delete',
        ];

        try {
            $this->controller->actionAdmin();
        } catch (\RuntimeException $e) {
            $this->assertStringContainsString('REDIRECT', $e->getMessage());
        }

        $stmt = $this->pdo->prepare("SELECT COUNT(*) FROM admin WHERE id_admin = 1");
        $stmt->execute();
        $this->assertSame(1, (int)$stmt->fetchColumn());

        $flashError = flash('error') ?? '';
        $this->assertStringContainsString('tidak dapat menghapus akun Anda sendiri', $flashError);
    }
}
